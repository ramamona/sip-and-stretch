// Every line Drip can say, grouped by personality.
//
// Contributing a line? Keep it under 110 characters, one or two emoji max, kind (roast gently,
// never mean), and free of health claims. `{name}` works anywhere; `{left}` only makes sense in
// `waterReminders` and `waterCheers`, and remember it can be 0.

extension Personality {
    public var pack: MessagePack {
        switch self {
        case .cheerful: return .cheerful
        case .sassy: return .sassy
        case .pirate: return .pirate
        case .zen: return .zen
        case .dramatic: return .dramatic
        case .robot: return .robot
        case .grandma: return .grandma
        case .gymBro: return .gymBro
        }
    }
}

